// Срок на ноде: подпись, бейдж и границы календаря.
// Разбор строки захвата и повторы живут в «даты.js» — здесь ТОЛЬКО то, что показывается
// человеку: dueLabel (подпись срока), dueBadge (с учётом выполнения) и короткая подпись для
// бейджа на ноде. Границы взяты те, на которых календарная арифметика ломается чаще всего:
// переход через год, високосный февраль и стык «шестой день / седьмой день», где dueLabel
// меняет формат с дня недели на число.месяца.
const t = [];
const Д = n => ymd(addDays(today(), n));

// ---- dueLabel: формат подписи по числу дней ----
t.push({имя:"без срока — подписи нет", ок: dueLabel(null) === null, факт: String(dueLabel(null))});

const вчера = dueLabel(Д(-1));
t.push({имя:"вчера — «просрочено 1д» и класс over",
        ок: !!вчера && вчера.cls === "over" && вчера.txt === "просрочено 1д",
        факт: вчера ? вчера.cls + " / " + вчера.txt : "нет"});

const пять = dueLabel(Д(-5));
t.push({имя:"минус пять дней — «просрочено 5д»",
        ок: !!пять && пять.txt === "просрочено 5д", факт: пять ? пять.txt : "нет"});

const сег = dueLabel(Д(0));
t.push({имя:"сегодня — класс today", ок: !!сег && сег.cls === "today" && сег.txt === "сегодня",
        факт: сег ? сег.cls + " / " + сег.txt : "нет"});

const зв = dueLabel(Д(1));
t.push({имя:"завтра — «завтра», без класса", ок: !!зв && зв.txt === "завтра" && зв.cls === "",
        факт: зв ? зв.cls + " / " + зв.txt : "нет"});

// от 2 до 6 дней dueLabel отдаёт ДЕНЬ НЕДЕЛИ, с 7 — число.месяца. Стык проверяем с обеих сторон:
// на нём легко промахнуться знаком сравнения и получить «вс» вместо даты через неделю.
const дни = ["вс","пн","вт","ср","чт","пт","сб"];
const шесть = dueLabel(Д(6));
t.push({имя:"через 6 дней — день недели",
        ок: !!шесть && дни.includes(шесть.txt) && шесть.txt === дни[parseYmd(Д(6)).getDay()],
        факт: шесть ? шесть.txt : "нет"});
const семь = dueLabel(Д(7));
t.push({имя:"через 7 дней — уже число.месяца, а не день недели",
        ок: !!семь && /^\d{1,2}\.\d{2}$/.test(семь.txt), факт: семь ? семь.txt : "нет"});
const месяц = dueLabel(Д(30));
t.push({имя:"через 30 дней — число.месяца",
        ок: !!месяц && /^\d{1,2}\.\d{2}$/.test(месяц.txt), факт: месяц ? месяц.txt : "нет"});

// ---- dueBadge: то же, но с учётом выполнения ----
// Проверяем на настоящих элементах, а не на выдуманных объектах: бейдж читает и done, и doneAt,
// и любая рассинхронизация этих трёх полей — это как раз то, что должно ловиться.
{
  const срок = Д(-3);
  const вовремя = {kind:"task", due: срок, done:true, doneAt:+parseYmd(Д(-4))};
  t.push({имя:"выполнено вовремя — бейджа нет", ок: dueBadge(вовремя) === null,
          факт: JSON.stringify(dueBadge(вовремя))});

  const опоздал = {kind:"task", due: срок, done:true, doneAt:+parseYmd(Д(-1))};
  const б = dueBadge(опоздал);
  t.push({имя:"выполнено с опозданием — «с опозданием 2д»",
          ок: !!б && б.cls === "late" && б.txt === "с опозданием 2д", факт: б ? б.txt : "нет"});

  const день_в_день = {kind:"task", due: срок, done:true, doneAt:+parseYmd(срок)};
  t.push({имя:"выполнено день в день — опоздания нет", ок: dueBadge(день_в_день) === null,
          факт: JSON.stringify(dueBadge(день_в_день))});

  const живая = {kind:"task", due: Д(-2), done:false};
  const б2 = dueBadge(живая);
  t.push({имя:"не выполнено и просрочено — «просрочено 2д»",
          ок: !!б2 && б2.cls === "over" && б2.txt === "просрочено 2д", факт: б2 ? б2.txt : "нет"});

  const безСрока = {kind:"task", due:null, done:false};
  t.push({имя:"нет срока — бейджа нет", ок: dueBadge(безСрока) === null,
          факт: JSON.stringify(dueBadge(безСрока))});
}

// ---- границы календаря ----
// Дни считаются через startOfDay, а не вычитанием миллисекунд: перевод часов и високосная
// секунда иначе дают 0.99 суток и «сегодня» превращается во «вчера».
t.push({имя:"31 декабря и 1 января — соседние дни",
        ок: daysBetween(parseYmd("2027-01-01"), parseYmd("2026-12-31")) === 1,
        факт: String(daysBetween(parseYmd("2027-01-01"), parseYmd("2026-12-31")))});
t.push({имя:"через границу года считается верно (25.12 → 05.01 = 11 дней)",
        ок: daysBetween(parseYmd("2027-01-05"), parseYmd("2026-12-25")) === 11,
        факт: String(daysBetween(parseYmd("2027-01-05"), parseYmd("2026-12-25")))});
t.push({имя:"високосный: 29.02.2028 существует", ок: !!makeDate(2028, 2, 29), факт:""});
t.push({имя:"невисокосный: 29.02.2027 не существует", ок: makeDate(2027, 2, 29) === null, факт:""});
t.push({имя:"високосный февраль: 28.02 → 29.02 = 1 день",
        ок: daysBetween(parseYmd("2028-02-29"), parseYmd("2028-02-28")) === 1,
        факт: String(daysBetween(parseYmd("2028-02-29"), parseYmd("2028-02-28")))});
t.push({имя:"невисокосный февраль: 28.02 → 01.03 = 1 день",
        ок: daysBetween(parseYmd("2027-03-01"), parseYmd("2027-02-28")) === 1,
        факт: String(daysBetween(parseYmd("2027-03-01"), parseYmd("2027-02-28")))});
t.push({имя:"подпись за 29.02 високосного года не пустая",
        ок: !!dueLabel("2028-02-29"), факт: JSON.stringify(dueLabel("2028-02-29"))});

// ---- короткая подпись бейджа на ноде ----
// Функции ещё нет в коде — она появится вместе с бейджем (см. docs/СРОК-ВИЗУАЛ.md).
// Сценарий не должен из-за этого краснеть: пока функции нет, честно говорим, сколько
// проверок пропущено, а как появится — они включатся сами, без правки этого файла.
if (typeof короткийСрок === "function"){
  const пары = [[-5,"-5"], [-1,"-1"], [0,"сег"], [1,"зв"], [3,"3"], [7,"7"], [30,"30"], [120,"99+"]];
  for (const [дн, ждём] of пары){
    const дано = короткийСрок(дн);
    t.push({имя:"короткая подпись " + дн + " → «" + ждём + "»", ок: дано === ждём, факт: String(дано)});
  }
  t.push({имя:"короткая подпись без срока — ничего", ок: короткийСрок(null) === null,
          факт: String(короткийСрок(null))});
} else {
  t.push({имя:"короткийСрок ещё не реализован — 9 проверок бейджа пропущено", ок:true,
          факт:"появится вместе с проходом «сроки» в _drawMain"});
}

// ---- узел графа знает число дней ----
// Бейдж рисуется по полю узла, а не по строке it.due: разбор строки в кадре — это 245 вызовов
// parseYmd на каждый кадр. Проверка включится, когда build начнёт класть «дней» в узел.
if (typeof graph !== "undefined" && graph && graph.nodes && graph.nodes.length){
  const есть = graph.nodes.some(n => n.дней !== undefined);
  t.push({имя: есть ? "узел несёт число дней до срока" : "build ещё не кладёт «дней» в узел — проверка пропущена",
          ок:true, факт: есть ? "поле есть" : "поля нет"});
}

return t;

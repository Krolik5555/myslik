// Разбор строки захвата и повторы.
// Тут живут случаи, на которых парсер уже ошибался: время «18.00» становилось сроком и резало
// название, 29 февраля уезжало на март, ежемесячный повтор с 31 числа пропускал февраль.
const t = [];
const разбор = s => { const p = parseCapture(s); return {название: p.title, срок: p.due}; };

const должноБытьБезСрока = ["созвон в 18.00", "купить 1.5 л молока", "обновить до 1.4 beta",
                            "версия v1.4.2 готова", "сдать 29.02", "купить 12.5 кг"];
for (const s of должноБытьБезСрока){
  const r = разбор(s);
  t.push({имя:"не выдумывает срок: «" + s + "»", ок: r.срок === null && r.название === s,
          факт:"«" + r.название + "» срок " + r.срок});
}

const должноПонять = {"встреча 25.12": 12, "отчёт 1.05": 5, "дедлайн 25.6": 6, "оплата 03.01.27": 1};
for (const [s, месяц] of Object.entries(должноПонять)){
  const r = разбор(s);
  const ок = !!r.срок && (+r.срок.split("-")[1]) === месяц;
  t.push({имя:"понимает дату: «" + s + "»", ок, факт: r.срок || "срока нет"});
}

// относительные даты
const завтра = ymd(addDays(today(), 1));
t.push({имя:"понимает «завтра»", ок: разбор("позвонить завтра").срок === завтра, факт: завтра});

// несуществующие даты не создаются
t.push({имя:"29.02 невисокосного года отвергается", ок: makeDate(2026, 2, 29) === null, факт:""});
t.push({имя:"29.02 високосного принимается", ок: !!makeDate(2028, 2, 29), факт:""});
t.push({имя:"31 апреля отвергается", ок: makeDate(2026, 4, 31) === null, факт:""});

// повторы
const завтраЖе = ymd(addDays(today(), 1));
t.push({имя:"ежедневный повтор — в будущее", ок: nextRepeat(ymd(today()), "daily") === завтраЖе, факт: завтраЖе});
t.push({имя:"просроченный повтор не рождается в прошлом",
        ок: nextRepeat("2025-01-10", "daily") > ymd(today()), факт: nextRepeat("2025-01-10", "daily")});
/* НЕ .endsWith("-31") — дата плавающая: следующее вхождение считается от «сегодня», а месяцы
   короче 31 дня клэмпят число вниз (так и задумано, см. core.js: nextRepeat, «анchor остаётся
   31»). Жёсткая «-31» ловила расхождение только в те дни, когда ближайшее вхождение само
   попадало в 31-дневный месяц — в остальные дни (как сегодня, сентябрь) тест был бы красным
   на РАБОЧЕМ коде. Проверяем инвариант без даты: число — это anchor(31) либо последний день
   месяца результата, и дата в будущем. */
const м = nextRepeat("2026-01-31", "monthly");
const мГод = м && +м.slice(0,4), мМес = м && +м.slice(5,7), мДень = м && +м.slice(8,10);
t.push({имя:"ежемесячный повтор держит число 31 или клэмпит до конца месяца", факт: м,
        ок: !!м && м > ymd(today()) && мДень === Math.min(31, daysInMonth(мГод, мМес))});
const м2 = nextRepeat("2026-03-31", "monthly");
t.push({имя:"ежемесячный повтор не проскакивает месяц", ок: !!м2 && м2 > ymd(today()), факт: м2});

/* ---------- свой календарь вместо системного ----------
   Нативный <input type="date"> открывал окно WebView2 — чужие шрифты и синие акценты Chromium
   посреди монохромного интерфейса. Проверяем не красоту, а контракт: значение по-прежнему
   строка YYYY-MM-DD в скрытом поле с тем же id, выбор дня его меняет, Escape закрывает ТОЛЬКО
   календарь, а не окно правки. */
{
  const ж = ms => new Promise(r => setTimeout(r, ms));
  closeOverlays();
  const зд = addItem({kind:"task", title:"Задача со сроком", due:null});
  openItemEditor(зд); await ж(350);
  const поле = () => document.querySelector("#f-due");
  const кнопка = () => document.querySelector(".field .date-ctl [data-datepick]");
  t.push({имя:"нативного пикера в окне правки больше нет",
          ок: !!поле() && поле().type === "hidden" && !document.querySelector('.modal input[type="date"]') && !!кнопка(),
          факт: "поле: " + (поле() ? поле().type : "нет") + ", кнопка: " + (кнопка() ? "есть" : "нет")});

  кнопка().click(); await ж(120);
  const поп = () => document.querySelector("#date-pop");
  const дней = поп() ? поп().querySelectorAll(".dp-d[data-d]").length : 0;
  t.push({имя:"календарь открывается кнопкой и показывает целый месяц",
          ок: !!поп() && дней >= 28 && дней <= 31
              && поп().querySelectorAll(".dp-wd")[0].textContent === "пн",
          факт: "дней в сетке " + дней + ", неделя начинается с «" +
                (поп() ? поп().querySelectorAll(".dp-wd")[0].textContent : "?") + "»"});

  // выбор дня пишет значение в том же формате, что писал нативный input
  const д15 = [...поп().querySelectorAll(".dp-d[data-d]")].find(b => b.textContent.trim().startsWith("15"));
  const ждали = д15.dataset.d;
  д15.click(); await ж(150);
  t.push({имя:"выбор дня кладёт дату строкой YYYY-MM-DD и закрывает календарь",
          ок: поле().value === ждали && /^\d{4}-\d{2}-\d{2}$/.test(поле().value) && !поп(),
          факт: "в поле «" + поле().value + "», календарь " + (поп() ? "остался" : "закрыт")});

  // крестик снимает срок, не открывая календарь
  document.querySelector(".field .date-ctl [data-dateclear]").click(); await ж(120);
  t.push({имя:"крестик снимает срок и календарь при этом не открывается",
          ок: поле().value === "" && !поп(), факт: "в поле «" + поле().value + "»"});

  // быстрая кнопка «завтра» — то, ради чего календарь и открывают чаще всего
  кнопка().click(); await ж(120);
  поп().querySelector('[data-q="1"]').click(); await ж(120);
  const завтра = new Date(today()); завтра.setDate(завтра.getDate() + 1);
  t.push({имя:"быстрая кнопка «завтра» ставит завтрашний день",
          ок: поле().value === ymd(завтра), факт: "в поле " + поле().value + ", ждали " + ymd(завтра)});

  /* Escape закрывает КАЛЕНДАРЬ, а не окно: глобальный обработчик приложения закрывает оверлеи,
     и без перехвата один нажим уносил бы всю правку. */
  кнопка().click(); await ж(120);
  document.dispatchEvent(new KeyboardEvent("keydown", {key:"Escape", bubbles:true}));
  await ж(120);
  t.push({имя:"Escape закрывает календарь, а окно правки остаётся",
          ок: !поп() && !!document.querySelector("#f-title"),
          факт: "календарь " + (поп() ? "открыт" : "закрыт") + ", окно " +
                (document.querySelector("#f-title") ? "на месте" : "закрылось")});

  // и сохранение окна доносит срок до ноды — тот же путь, что был у нативного поля
  document.querySelector("#f-save").click(); await ж(200);
  t.push({имя:"срок из своего календаря доезжает до ноды по «Сохранить»",
          ок: зд.due === ymd(завтра), факт: "в ноде " + зд.due});

  /* Календарь живёт в body, а его якорь — в окне. Кнопку может унести закрытие окна
     (closeOverlays чистит #overlay-root целиком) или переключение типа на «заметку» (блок срока
     тогда просто прячется). Без сторожа попап оставался висеть на экране сам по себе. */
  openItemEditor(зд); await ж(300);
  кнопка().click(); await ж(120);
  const открылся = !!поп();
  closeOverlays(); await ж(200);
  t.push({имя:"закрытие окна уносит и открытый календарь",
          ок: открылся && !поп(), факт: "открывался: " + открылся + ", после закрытия: " + (поп() ? "висит" : "снят")});

  openItemEditor(зд); await ж(300);
  кнопка().click(); await ж(120);
  document.querySelector('#f-kind [data-k="note"]').click(); await ж(200);
  t.push({имя:"переключение на заметку прячет срок вместе с календарём",
          ок: !поп(), факт: поп() ? "календарь висит над скрытым полем" : "снят"});
  closeOverlays(); hardDeleteItem(зд.id);
}

// битый срок вычищается при загрузке
const s3 = sanitizeState({areas:[], links:[], settings:{},
  items:[{id:"x", title:"а", due:"2026-02-31"}, {id:"y", title:"б", due:"2026-12-25"}]});
t.push({имя:"несуществующий срок вычищается при загрузке",
        ок: s3.items[0].due === null && s3.items[1].due === "2026-12-25",
        факт: JSON.stringify(s3.items.map(i => i.due))});
return t;

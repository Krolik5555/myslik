// Разбор строки захвата и повторы.
// Тут живут случаи, на которых парсер уже ошибался: время «18.00» становилось сроком и резало
// название, 29 февраля уезжало на март, ежемесячный повтор с 31 числа пропускал февраль.
const t = [];
const разбор = s => { const p = parseCapture(s); return {название: p.title, срок: p.due}; };

const должноБытьБезСрока = ["созвон в 18.00", "купить 1.5 л молока", "обновить до 1.4 beta",
                            "версия v1.4.2 готова", "сдать 29.02", "купить 12.5 кг"];
for (const s of должноБытьБезСрока){
  const r = разбор(s);
  t.push({имя:"не выдумывает срок: «" + s + "»", ок: r.срок === null && r.название === s,
          факт:"«" + r.название + "» срок " + r.срок});
}

const должноПонять = {"встреча 25.12": 12, "отчёт 1.05": 5, "дедлайн 25.6": 6, "оплата 03.01.27": 1};
for (const [s, месяц] of Object.entries(должноПонять)){
  const r = разбор(s);
  const ок = !!r.срок && (+r.срок.split("-")[1]) === месяц;
  t.push({имя:"понимает дату: «" + s + "»", ок, факт: r.срок || "срока нет"});
}

// относительные даты
const завтра = ymd(addDays(today(), 1));
t.push({имя:"понимает «завтра»", ок: разбор("позвонить завтра").срок === завтра, факт: завтра});

// несуществующие даты не создаются
t.push({имя:"29.02 невисокосного года отвергается", ок: makeDate(2026, 2, 29) === null, факт:""});
t.push({имя:"29.02 високосного принимается", ок: !!makeDate(2028, 2, 29), факт:""});
t.push({имя:"31 апреля отвергается", ок: makeDate(2026, 4, 31) === null, факт:""});

// повторы
const завтраЖе = ymd(addDays(today(), 1));
t.push({имя:"ежедневный повтор — в будущее", ок: nextRepeat(ymd(today()), "daily") === завтраЖе, факт: завтраЖе});
t.push({имя:"просроченный повтор не рождается в прошлом",
        ок: nextRepeat("2025-01-10", "daily") > ymd(today()), факт: nextRepeat("2025-01-10", "daily")});
const м = nextRepeat("2026-01-31", "monthly");
t.push({имя:"ежемесячный повтор держит 31 число", ок: !!м && м.endsWith("-31") && м > ymd(today()), факт: м});
const м2 = nextRepeat("2026-03-31", "monthly");
t.push({имя:"ежемесячный повтор не проскакивает месяц", ок: !!м2 && м2 > ymd(today()), факт: м2});

// битый срок вычищается при загрузке
const s3 = sanitizeState({areas:[], links:[], settings:{},
  items:[{id:"x", title:"а", due:"2026-02-31"}, {id:"y", title:"б", due:"2026-12-25"}]});
t.push({имя:"несуществующий срок вычищается при загрузке",
        ок: s3.items[0].due === null && s3.items[1].due === "2026-12-25",
        факт: JSON.stringify(s3.items.map(i => i.due))});
return t;

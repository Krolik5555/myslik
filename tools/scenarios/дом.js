// ================== 7. НОДЫ ПЕРЕТЕКАЮТ В ДОМА, А НЕ ВЛЕТАЮТ ==================
/* Самое ценное в этом режиме по мнению КРОЛИКА: включаешь тумблер — и ноды ПЛАВНО перетекают
   по своим местам. Ломается это одним числом (жёсткость домашней пружины), и ломается
   незаметно: форма при жёсткой пружине держится даже лучше, просто ноды влетают в дома
   рывком за десяток кадров. Поэтому меряем не «доехали ли», а КАК: пик шага за кадр. */
{
  const дом = it => { const о = graph.byId[it.parent] || graph.byId["hub_" + it.area];
                      return о ? {x: о.x + it.hx, y: о.y + it.hy} : null; };
  const цели = graph.nodes.filter(n => n.ref && n.ref.hx != null);
  // разводим ноды от домов: физика без дома растащит их сама
  /* Разводим РУКАМИ и на фиксированные 45 px, а не физикой. Физика на демо расшвыривает ноды
     на сотни пикселей, а дальше сотни любая нода упирается в общий потолок смещения (16 px за
     кадр) независимо от жёсткости дома — и проверка перестаёт мерить дом. Плюс фиксированный
     отрыв делает замер воспроизводимым от прогона к прогону. */
  S.settings.graphHome = false;
  цели.forEach((n, i) => { const h = дом(n.ref), a = i * 1.7;
    n.x = h.x + Math.cos(a) * 45; n.y = h.y + Math.sin(a) * 45; n.vx = 0; n.vy = 0; });
  const отрыв = Math.max(...цели.map(n => { const h = дом(n.ref); return Math.hypot(n.x - h.x, n.y - h.y); }));
  S.settings.graphHome = true; graph.alpha = 0.3;   // ровно столько ставит toggleHome
  let кадров = 0, доехали = -1;
  while (graph.alpha > 0 && кадров < 3000) {
    graph._tick(true); кадров++;
    const макс = Math.max(...цели.map(n => { const h = дом(n.ref); return Math.hypot(n.x - h.x, n.y - h.y); }));
    if (доехали < 0 && макс < 10) доехали = кадров;
  }
  const промах = Math.max(...цели.map(n => { const h = дом(n.ref); return Math.hypot(n.x - h.x, n.y - h.y); }));
  /* Меряем ВРЕМЯ перетекания, а не пик шага: пик ловит скачок первого кадра (ноды сюда
     поставлены телепортом, и раскладочные силы отвечают на это разом), а не работу дома.
     Порог снизу и есть суть проверки: при жёсткой пружине ноды влетают в дома за десяток
     кадров — замер по шкале давал 16 кадров при k=0.2 против 87 при 0.05. */
  t.push({имя: "ноды перетекают в дома плавно, а не влетают", ок: отрыв > 5 && доехали > 30,
          факт: "отрыв был " + отрыв.toFixed(0) + " px · доехали за " + доехали +
                " кадров (рывок — это меньше 30) · осело за " + кадров});
  /* НЕВЯЗКА В НЕСКОЛЬКО ПИКСЕЛЕЙ — СОЗНАТЕЛЬНЫЙ РАЗМЕН. Домашняя пружина мягкая И умножается
     на alpha (иначе форма плавает под рукой — см. ДОМ_СИЛА в graph.js), а физика при alpha=0
     останавливается вовсе. Значит на доезд у пружины есть только время остывания, и последние
     пикселей пять она добрать не успевает: включение тумблера поднимает alpha всего до 0.3.
     Само по себе это неважно — важно, НАКАПЛИВАЕТСЯ ли невязка: если каждое возмущение
     оставляет свои пять пикселей и они складываются, форма уплывёт за день работы.
     Гоняем пять циклов «растащили — отпустили» и сравниваем начало с концом ПО ПАРАМ: отдельный
     цикл шумит (замер: 7.1 → 7.8 → 3.6 → 1.5 → 6.8), и сравнение одиночных значений ловило бы
     этот шум вместо накопления. */
  const промахи = [промах];
  for (let ц = 0; ц < 4; ц++) {
    цели.forEach((n, i) => { const h = дом(n.ref), a = i * 1.7 + ц;
      n.x = h.x + Math.cos(a) * 45; n.y = h.y + Math.sin(a) * 45; n.vx = 0; n.vy = 0; });
    graph.alpha = 0.3;
    let к = 0; while (graph.alpha > 0 && к < 3000) { graph._tick(true); к++; }
    промахи.push(Math.max(...цели.map(n => { const h = дом(n.ref); return Math.hypot(n.x - h.x, n.y - h.y); })));
  }
  const нач = (промахи[0] + промахи[1]) / 2, кон = (промахи[3] + промахи[4]) / 2;
  t.push({имя: "и всё-таки доезжают", ок: Math.max(...промахи) < 12,
          факт: "промахи по циклам: " + промахи.map(п => п.toFixed(1)).join(" → ") + " px"});
  t.push({имя: "невязка не накапливается", ок: кон - нач < 2,
          факт: "первые два цикла " + нач.toFixed(1) + " px, последние два " + кон.toFixed(1) + " px"});
}


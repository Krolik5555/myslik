// ПОДГРАФ (нода kind:"sub" со своим графом внутри).
// Проверяем не картинку, а обещания, которые легко сломать невидимо: содержимое лежит
// отдельной записью в S.graphs, ключ выведен из id ноды, областей внутри нет, а удаление,
// копирование и откат обязаны таскать внутренность за нодой. Всё это молчаливые связи —
// сломавшись, они не падают, а тихо теряют данные.
const t = [];
const ж = ms => new Promise(r => setTimeout(r, ms));
const ошибки = [];
const прежний = console.error;
console.error = (...a) => { ошибки.push(a.join(" ")); прежний(...a); };

const корневой = S.settings.graph;
const мусор = [];                       // что снести в конце, чтобы не засорять демо

// ---------- заведение ----------
view = "notes"; render(); await ж(120);
const узел = addItem({kind:"sub", title:"Проверочный подграф", status:"todo"});
узел.x = 0; узел.y = 0; мусор.push(узел.id);
t.push({имя:"нода-подграф заводится", ок: узел.kind === "sub" && !!узел.id, факт: узел.id});
t.push({имя:"подграф завершаемый (kindIsTask)", ок: kindIsTask("sub") === true,
        факт: "статусы: " + статусыДляВида("sub").join(",")});

// граф заводится ЛЕНИВО: до первого входа записи в S.graphs быть не должно
t.push({имя:"внутренний граф до входа не заведён", ок: subGraphOf(узел.id) === null, факт: ""});

// ---------- вход ----------
const вошли = subEnter(узел);
t.push({имя:"двойной клик уводит внутрь (subEnter)", ок: вошли === true && S.settings.graph === subKey(узел.id),
        факт: S.settings.graph});
t.push({имя:"внутри пусто и своё", ок: S.items.length === 0 && S.areas.length === 0,
        факт: S.items.length + " нод, " + S.areas.length + " областей"});
t.push({имя:"inSubGraph видит, что мы внутри", ок: inSubGraph() === true, факт: ""});

// ---------- корневой узел ----------
render(); await ж(140);
const rid = subRootId(узел.id);
const кор = graph ? graph.byId[rid] : null;
t.push({имя:"корень подграфа стоит на холсте", ок: !!кор, факт: rid});
t.push({имя:"корень носит ЖИВОЕ имя ноды-владельца", ок: !!кор && кор.label === узел.title,
        факт: кор ? кор.label : ""});
t.push({имя:"корня нет в S.items — удалять нечего", ок: !S.items.some(i => i.id === rid), факт: ""});
// Delete по одному корню обязан отказать, а не снести молча
if (graph){
  graph.selNodes = new Set([rid]);
  await graph.deleteSelected(); await ж(60);
  t.push({имя:"Delete не сносит корень", ок: !!(graph && graph.byId[rid]), факт: ""});
  graph.selNodes.clear();
}

// крошки над холстом ведут наружу
const крошки = document.querySelectorAll("#g-crumbs [data-crumb]");
t.push({имя:"крошки показывают путь наружу", ок: крошки.length >= 1 && !!document.querySelector("#g-crumb-up"),
        факт: крошки.length + " кликабельных звена"});
// внутри подграфа областей не предлагают вовсе
t.push({имя:"полоса слева прячет области", ок: document.querySelector("#side").classList.contains("in-sub"), факт: ""});

// ---------- содержимое ----------
const внутр1 = addItem({kind:"note", title:"Внутренняя заметка"});
const внутр2 = addItem({kind:"task", title:"Внутренняя задача", status:"todo"});
внутр1.x = -80; внутр1.y = 0; внутр2.x = 80; внутр2.y = 0;
addLink(внутр1.id, внутр2.id);
const внутрId = [внутр1.id, внутр2.id];
t.push({имя:"ноды кладутся внутрь подграфа", ок: S.items.length === 2 && S.links.length === 1,
        факт: S.items.length + " нод, " + S.links.length + " связей"});

// ИЕРАРХИЯ ОТ КОРНЯ — ради него он и заведён: без точки отсчёта BFS в recomputeHierarchy
// стартовать неоткуда (внутри подграфа областей нет), и всё дерево оставалось плоским.
addLink(rid, внутр1.id);
recomputeHierarchy();
t.push({имя:"связь с корнем делает ноду верхним уровнем", ок: внутр1.parent === null, факт: "parent: " + внутр1.parent});
t.push({имя:"дальше дерево строится от неё", ок: внутр2.parent === внутр1.id,
        факт: "parent: " + внутр2.parent + " (ждали " + внутр1.id + ")"});
t.push({имя:"область корень не раздаёт", ок: !внутр1.area && !внутр2.area,
        факт: "области: " + внутр1.area + " / " + внутр2.area});

// ---------- выход и возврат ----------
const вышли = subLeave();
t.push({имя:"subLeave возвращает на уровень выше", ок: вышли === true && S.settings.graph === корневой,
        факт: S.settings.graph});
t.push({имя:"снаружи внутренних нод не видно", ок: !S.items.some(i => внутрId.includes(i.id)),
        факт: "в корне нод: " + S.items.length});
t.push({имя:"внутренний граф не попал в список полосы", ок: !graphsTop().some(g => g.id === subKey(узел.id)),
        факт: "графов верхнего уровня: " + graphsTop().length});
t.push({имя:"корень ветки определяется (graphTopId)", ок: graphTopId() === корневой, факт: graphTopId()});

subEnter(узел);
t.push({имя:"повторный вход отдаёт то же содержимое", ок: S.items.length === 2 && S.links.length === 2,
        факт: S.items.length + " нод, " + S.links.length + " связей"});
subLeave();

// ---------- копия ноды делает копию содержимого ----------
const пак = subPack(узел.id);
const копия = addItem({kind:"sub", title:"Копия подграфа"});
мусор.push(копия.id);
subUnpack(копия.id, пак);
const гКоп = subGraphOf(копия.id);
const пересек = гКоп ? гКоп.items.filter(i => внутрId.includes(i.id)).length : -1;
t.push({имя:"копия получает СВОЁ содержимое", ок: !!гКоп && гКоп.items.length === 2 && гКоп.links.length === 2,
        факт: гКоп ? гКоп.items.length + " нод, " + гКоп.links.length + " связей" : "графа нет"});
t.push({имя:"у нод копии НОВЫЕ id (нет общих холстов)", ок: пересек === 0, факт: "совпало id: " + пересек});
// связь с корнем адресована id ноды-владельца: у копии владелец другой, значит и корень другой
{
  const свойКор = subRootId(копия.id), чужойКор = rid;
  const плохо = гКоп ? (гКоп.links||[]).filter(l => l[0] === чужойКор || l[1] === чужойКор).length : -1;
  const хорошо = гКоп ? (гКоп.links||[]).filter(l => l[0] === свойКор || l[1] === свойКор).length : -1;
  t.push({имя:"связь с корнем в копии переадресована на СВОЙ корень", ок: плохо === 0 && хорошо === 1,
          факт: "на чужой: " + плохо + ", на свой: " + хорошо});
}

// ---------- удаление уносит содержимое, откат возвращает ----------
const пакет = deletePack([копия.id]);
t.push({имя:"удаление ноды уносит её подграф", ок: subGraphOf(копия.id) === null, факт: ""});
restorePack(пакет);
const гВерн = subGraphOf(копия.id);
t.push({имя:"возврат ноды возвращает подграф с содержимым (карман удалённых)",
        ок: !!гВерн && гВерн.items.length === 2, факт: гВерн ? гВерн.items.length + " нод" : "не вернулся"});

// ---------- санитайзер держит правила ----------
{
  const снимок = JSON.parse(JSON.stringify({settings:S.settings, graphs:S.graphs, boards:{}, media:{}, tags:S.tags, templates:S.templates}));
  // 1. область, занесённая внутрь подграфа чужим json, обязана исчезнуть
  const вн = снимок.graphs.find(g => g.id === subKey(узел.id));
  вн.areas = [{id:"a_проверка", name:"Чужая область", icon:"ti-folder"}];
  вн.items[0].area = "a_проверка";
  // 2. связь с ЧУЖИМ корнем — указывает в никуда: у подграфа корень ровно один
  вн.links.push([subRootId("посторонний"), вн.items[0].id]);
  // 3. подграф без ноды-владельца — мусор, который иначе останется в файле невидимкой
  снимок.graphs.push({id:"gs_никого_нет", name:"Сирота", items:[{id:"x_сирота", title:"", kind:"note"}], areas:[], links:[]});
  const чист = sanitizeState(снимок);
  const внЧист = чист.graphs.find(g => g.id === subKey(узел.id));
  t.push({имя:"санитайзер вычищает области внутри подграфа",
          ок: !!внЧист && внЧист.areas.length === 0 && внЧист.items.every(i => i.area === null),
          факт: внЧист ? внЧист.areas.length + " областей" : "граф пропал"});
  t.push({имя:"санитайзер выкидывает связь с чужим корнем",
          ок: !!внЧист && !(внЧист.links||[]).some(l => isRootId(l[0]) && l[0] !== rid || isRootId(l[1]) && l[1] !== rid),
          факт: внЧист ? внЧист.links.length + " связей" : ""});
  t.push({имя:"свою связь с корнем санитайзер сохраняет",
          ок: !!внЧист && (внЧист.links||[]).some(l => l[0] === rid || l[1] === rid), факт: ""});
  t.push({имя:"санитайзер сносит подграф без владельца",
          ок: !чист.graphs.some(g => g.id === "gs_никого_нет"), факт: "графов: " + чист.graphs.length});
}

/* ---------- раскладка переживает уход из графа ----------
   Вход в подграф и выход обратно — это два полных render(), то есть два пересоздания графа.
   Живые координаты узлов уезжают в данные только по остыванию симуляции, поэтому снос
   экземпляра обязан их дожать (flushLayout) — иначе возврат поднимал раскладку многосекундной
   давности, а при включённом «Держать раскладку» ноды после первого же клика ехали по домам. */
{
  view = "notes"; render(); await ж(140);
  const n = graph ? graph.nodes.find(x => x.ref) : null;
  if (!n) t.push({имя:"живая раскладка уезжает в данные до сноса графа", ок:false, факт:"на холсте нет узлов"});
  else {
    const былX = n.ref.x;
    n.x = (n.x || 0) + 137; n.y = (n.y || 0) + 91;   // «физика развела узлы» — в данные это ещё не попало
    graph._moved = true;
    graph.flushLayout();
    t.push({имя:"живая раскладка уезжает в данные до сноса графа",
            ок: n.ref.x === n.x && n.ref.x !== былX, факт: былX + " → " + n.ref.x});
    t.push({имя:"повторный дожим вхолостую не пишет", ок: graph.flushLayout() === false, факт:""});
  }
}

// ---------- уборка ----------
мусор.forEach(id => { const it = S.items.find(i => i.id === id); if (it) hardDeleteItem(id); });
if (S.settings.graph !== корневой) graphSwitch(корневой);
render(); await ж(120);
t.push({имя:"после уборки подграфов не осталось",
        ок: !мусор.some(id => subGraphOf(id)), факт: ""});

console.error = прежний;
t.push({имя:"консоль чистая", ок: ошибки.length === 0, факт: ошибки.slice(0, 2).join(" | ")});
return t;

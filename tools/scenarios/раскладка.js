const o = (ax,ay,bx,by,cx,cy) => (bx-ax)*(cy-ay)-(by-ay)*(cx-ax);
/* Один прогон: выделить, упорядочить, снять цели по цепочке домов и промерить. */
async function мерить(метка, выделение, центрId) {
  graph.selNodes = new Set(выделение.map(n => n.id)); graph._paintSel();
  const t0 = performance.now();
  const ок = graph._tidySelection();
  const мс = Math.round(performance.now() - t0);
  await ж(150);
  const цел = new Map();
  // корни цепочек — закреплённые узлы: их цель = живое место
  выделение.forEach(it => { if (it.pin) { const жн = graph.byId[it.id]; if (жн) цел.set(it.id, {x: жн.x, y: жн.y}); } });
  // цепочка «дом от дома владельца» разворачивается за несколько проходов: порядок узлов произволен
  for (let раунд = 0; раунд < 6; раунд++) {
    выделение.forEach(it => { if (цел.has(it.id) || it.hx == null) return; const oo = homeOwner(it); if (!oo) return;
      const б = цел.get(oo.id) || (!выделение.some(x => x.id === oo.id) && oo.x != null ? {x:oo.x, y:oo.y} : null); if (!б) return;
      цел.set(it.id, {x: б.x + it.hx, y: б.y + it.hy}); });
  }
  const ц = цел.get(центрId) || {x:0, y:0};
  const радиусы = ветки.map(в => { const p = цел.get(в.id); return p ? Math.round(Math.hypot(p.x - ц.x, p.y - ц.y)) : -1; });
  const макс = свои.reduce((m, n) => { const p = цел.get(n.id); return p ? Math.max(m, Math.hypot(p.x - ц.x, p.y - ц.y)) : m; }, 0);
  const сег = связи.map(l => ({a:l[0], b:l[1], p:цел.get(l[0]), q:цел.get(l[1])})).filter(s => s.p && s.q);
  let пересечений = 0, пары = [];
  for (let i = 0; i < сег.length; i++) for (let j = i + 1; j < сег.length; j++) {
    const s = сег[i], r = сег[j];
    if (s.a === r.a || s.a === r.b || s.b === r.a || s.b === r.b) continue;
    const o1 = o(s.p.x,s.p.y,s.q.x,s.q.y,r.p.x,r.p.y), o2 = o(s.p.x,s.p.y,s.q.x,s.q.y,r.q.x,r.q.y);
    const o3 = o(r.p.x,r.p.y,r.q.x,r.q.y,s.p.x,s.p.y), o4 = o(r.p.x,r.p.y,r.q.x,r.q.y,s.q.x,s.q.y);
    if ((o1>0)!==(o2>0) && (o3>0)!==(o4>0)) { пересечений++; if (пары.length < 4) пары.push(имя[s.a]+">"+имя[s.b]+" × "+имя[r.a]+">"+имя[r.b]); }
  }
  const кустНоды = id => { const m = /(ветка|лист|внук)(\d+)/.exec(имя[id] || ""); return m ? m[2] : "корень"; };
  // нода, лежащая на ЧУЖОЙ связи (ближе 16 px), читается как связанная с ней — считаем и это
  let наЛинии = 0, наКом = [];
  сег.forEach(s => { свои.forEach(n => { if (n.id === s.a || n.id === s.b) return; const p = цел.get(n.id); if (!p) return;
    if (кустНоды(n.id) === кустНоды(s.b) && кустНоды(n.id) !== "корень") return;   // своя ветка — теснота, не чужой луч
    const dx = s.q.x - s.p.x, dy = s.q.y - s.p.y, L2 = dx*dx + dy*dy || 1;
    const tt = Math.max(0, Math.min(1, ((p.x - s.p.x)*dx + (p.y - s.p.y)*dy) / L2));
    const d = Math.hypot(s.p.x + dx*tt - p.x, s.p.y + dy*tt - p.y);
    if (d < 16) { наЛинии++; if (наКом.length < 4) наКом.push(имя[n.id] + " на " + имя[s.a] + ">" + имя[s.b] + " (" + Math.round(d) + ")"); } }); });
  // теснота: минимальное расстояние между любыми двумя нодами — подписи шириной с три ноды
  let минПара = 1e9, минЧужие = 1e9;
  const сп = свои.filter(n => цел.has(n.id));
  for (let i = 0; i < сп.length; i++) for (let j = i + 1; j < сп.length; j++) {
    const a = цел.get(сп[i].id), b = цел.get(сп[j].id); const d = Math.hypot(a.x - b.x, a.y - b.y);
    if (d < минПара) минПара = d;
    if (кустНоды(сп[i].id) !== кустНоды(сп[j].id) && d < минЧужие) минЧужие = d;
  }
  const доЧужих = чужие.reduce((m, ч) => Math.min(m, свои.reduce((mm, n) => { const p = цел.get(n.id); return p ? Math.min(mm, Math.hypot(p.x - ч.x, p.y - ч.y)) : mm; }, 1e9)), 1e9);
  // цепочка: дальнее звено — не дальше 420 px от своей ветки (прямая по 100 давала 1200)
  const цв = ветки[15], цц = цел.get(цв.id);
  const цепьМакс = цц ? свои.filter(n => /^лист15-/.test(имя[n.id] || "")).reduce((m, n) => { const q = цел.get(n.id); return q ? Math.max(m, Math.hypot(q.x - цц.x, q.y - цц.y)) : m; }, 0) : -1;
  // цепочка с развилкой: ни одна связь в ней не длиннее 220 px (у КРОЛИКА были по 700)
  const развилка = свои.filter(n => /^(ветка|лист)14/.test(имя[n.id] || "")).map(n => n.id);
  const длиннаяСвязь = сег.filter(sg => развилка.includes(sg.a) && развилка.includes(sg.b)).reduce((m, sg) => Math.max(m, Math.hypot(sg.q.x - sg.p.x, sg.q.y - sg.p.y)), 0);
  const п = метка + ": ";
  t.push({имя:п+"цепочка с развилкой не растягивается", ок: длиннаяСвязь > 0 && длиннаяСвязь <= 220, факт: "самая длинная связь " + Math.round(длиннаяСвязь) + " px (норма ≤220)"});
  t.push({имя:п+"цепочка сворачивается, а не улетает", ок: цепьМакс >= 0 && цепьМакс <= 680, факт: "дальнее звено в " + Math.round(цепьМакс) + " px от ветки (норма ≤680 — ловит возврат к прямой в 1200; змейка целиком даёт ~230, в тесноте сдвигается наружу рядами)"});
  t.push({имя:п+"раскладка отработала и дала цели всем", ок: ок === true && свои.every(n => цел.has(n.id)), факт: "целей " + свои.filter(n => цел.has(n.id)).length + " из " + свои.length + ", " + мс + " мс"});
  t.push({имя:п+"ветки на разных удалениях (кусты вложены, а не кольцо и не спицы)", ок: Math.min(...радиусы) < 220 && Math.max(...радиусы) < 640,
          факт: радиусы.join(" ")});
  t.push({имя:п+"дерево компактно", ок: макс <= 880, факт: "самая дальняя нода в " + Math.round(макс) + " px от корня (норма ≤880 для дерева в 117 нод с двумя цепочками; референс на 91 ноде ≈480)"});
  t.push({имя:п+"но не каша: чужие ноды не ближе 50 px, свои — 34", ок: минЧужие >= 50 && минПара >= 34,
          факт: "чужие " + Math.round(минЧужие) + " px, любые " + Math.round(минПара) + " px"});
  t.push({имя:п+"связи не пересекаются", ок: пересечений === 0, факт: пересечений + " из " + сег.length + (пары.length ? " — " + пары.join(", ") : "")});
  t.push({имя:п+"нода не лежит на чужой связи", ок: наЛинии === 0, факт: наЛинии + (наКом.length ? " — " + наКом.join(", ") : "")});
  t.push({имя:п+"чужие ноды рядом не накрыты", ок: доЧужих >= 40, факт: "ближайшая цель в " + Math.round(доЧужих) + " px"});
  undoStep(); await ж(150);   // шаг раскладки лёг в историю — вернуть как было перед следующим прогоном
  graph.selNodes.clear(); graph._paintSel();
}


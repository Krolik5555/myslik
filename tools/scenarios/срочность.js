// Вычисляемая срочность: urgency(it) и urgencyLevel(it).
// Формула и веса — в docs/СРОЧНОСТЬ.md. Здесь проверяется не «красиво ли получилось», а три
// вещи, на которых такие формулы ломаются: (1) вырожденные данные — импорт без сроков и
// приоритетов не должен давать ни ложных нулей, ни ложных единиц; (2) порядок входов —
// просрочка обязана перевешивать приоритет, иначе наверх лезут вечные «важные» проекты;
// (3) отбор горящих — их число обязано быть ограничено, иначе граф становится ёлкой.
const t = [];
const Д = n => ymd(addDays(today(), n));

if (typeof urgency !== "function"){
  t.push({имя:"urgency ещё не реализована — 20 проверок пропущено", ок:true,
          факт:"появится в core.js рядом с dueLabel, см. docs/СРОЧНОСТЬ.md"});
  return t;
}

// Собираем элементы через addItem, а не литералами: формула читает те же поля, что кладёт
// конструктор (updated, status, priority), и рассинхрон конструктора с формулой должен ловиться.
const мусор = [];
const задача = (о) => { const it = addItem(Object.assign({kind:"task", title:"проверка срочности"}, о));
                        мусор.push(it); return it; };

// ---- вырожденные случаи ----
{
  const пустая = задача({});
  t.push({имя:"свежая задача без срока и приоритета — ноль", ок: urgency(пустая) === 0,
          факт: String(urgency(пустая))});
  t.push({имя:"у неё уровень 0", ок: urgencyLevel(пустая) === 0, факт: String(urgencyLevel(пустая))});

  const заметка = addItem({kind:"note", title:"заметка"}); мусор.push(заметка);
  t.push({имя:"заметка срочности не имеет", ок: urgency(заметка) === 0, факт: String(urgency(заметка))});

  const готовая = задача({due: Д(-30), priority:3});
  готовая.done = true; готовая.status = "done";
  t.push({имя:"выполненная задача не горит, даже просроченная на месяц",
          ок: urgency(готовая) === 0, факт: String(urgency(готовая))});
}

// ---- границы шкалы ----
{
  const год = задача({due: Д(-365)});
  const u = urgency(год);
  t.push({имя:"просрочено на год — в пределах 0..1", ок: u > 0 && u <= 1, факт: u.toFixed(3)});
  t.push({имя:"просрочено на год — уровень не ниже 2", ок: urgencyLevel(год) >= 2,
          факт: String(urgencyLevel(год))});

  const потолок = задача({due: Д(-365), priority:3, status:"doing"});
  t.push({имя:"худший случай не вылезает за 1", ок: urgency(потолок) <= 1, факт: urgency(потолок).toFixed(3)});
  t.push({имя:"худший случай — уровень 3", ок: urgencyLevel(потолок) === 3, факт: String(urgencyLevel(потолок))});
}

// ---- порядок входов ----
{
  const просроч = задача({due: Д(-1)});
  const важная = задача({priority: 3});
  t.push({имя:"просроченная вчера важнее задачи с приоритетом 3 и без срока",
          ок: urgency(просроч) > urgency(важная),
          факт: urgency(просроч).toFixed(2) + " против " + urgency(важная).toFixed(2)});

  const сегодня = задача({due: Д(0)});
  const завтра = задача({due: Д(1)});
  const неделя = задача({due: Д(7)});
  const далеко = задача({due: Д(60)});
  const монотонно = urgency(просроч) >= urgency(сегодня) && urgency(сегодня) > urgency(завтра)
                 && urgency(завтра) > urgency(неделя) && urgency(неделя) > urgency(далеко);
  t.push({имя:"чем ближе срок, тем выше срочность (монотонность)", ок: монотонно,
          факт: [просроч, сегодня, завтра, неделя, далеко].map(x => urgency(x).toFixed(2)).join(" > ")});

  const безСрока = задача({});
  t.push({имя:"далёкий срок всё же выше, чем полное его отсутствие",
          ок: urgency(далеко) > urgency(безСрока),
          факт: urgency(далеко).toFixed(3) + " против " + urgency(безСрока).toFixed(3)});
}

// ---- статус двигает балл в нужную сторону ----
{
  const база = задача({due: Д(2)});
  const b = urgency(база);
  const работа = задача({due: Д(2), status:"doing"});
  const пауза = задача({due: Д(2), status:"paused"});
  t.push({имя:"«в работе» поднимает срочность", ок: urgency(работа) > b,
          факт: urgency(работа).toFixed(2) + " против " + b.toFixed(2)});
  /* «НА ПАУЗЕ» НЕ ГОРИТ НИКОГДА, а не просто ниже (2026-09-01, по прямой просьбе КРОЛИКА:
     «если он на паузе, то гореть не должен»). Раньше пауза была скидкой (−0,15) в общей сумме,
     и задача с высоким приоритетом или горящим сроком всё равно могла пробиться в горящие —
     хотя отложил её сам человек. Проверяем на ХУДШЕМ случае: просрочка на год, максимальный
     приоритет, пауза — балл обязан остаться ровно нулём, а не просто «ниже базы». */
  t.push({имя:"«на паузе» — это ноль, а не просто ниже", ок: urgency(пауза)===0,
          факт: urgency(пауза).toFixed(3)});
  const паузаНоЖуть = задача({due: Д(-365), priority: 3, status: "paused"});
  t.push({имя:"пауза перебивает даже просрочку на год с приоритетом 3",
          ок: urgency(паузаНоЖуть)===0, факт: urgency(паузаНоЖуть).toFixed(3)});

  // waiting появится вместе со словарём из docs/СТАТУСЫ.md — проверяем, только если он уже есть
  const ждёт = задача({due: Д(2), status:"waiting"});
  if (ждёт.status === "waiting"){
    t.push({имя:"«ждёт» опускает, но не обнуляет (срок продолжает тикать)",
            ок: urgency(ждёт) < b && urgency(ждёт) > 0,
            факт: urgency(ждёт).toFixed(2) + " против " + b.toFixed(2)});
  } else {
    t.push({имя:"статус waiting ещё не в словаре — проверка пропущена", ок:true,
            факт:"санитайзер свёл его к " + ждёт.status});
  }
}

// ---- застой не перевешивает срок ----
{
  const старая = задача({});
  старая.updated = Date.now() - 90 * 86400000;      // забыта на три месяца
  const срочная = задача({due: Д(0)});
  t.push({имя:"забытая на три месяца не обгоняет задачу со сроком «сегодня»",
          ок: urgency(срочная) > urgency(старая),
          факт: urgency(срочная).toFixed(2) + " против " + urgency(старая).toFixed(2)});
  t.push({имя:"но застой всё же поднимает балл выше нуля", ок: urgency(старая) > 0,
          факт: urgency(старая).toFixed(3)});
}

// ---- отбор горящих: число ограничено, вырожденность ловится ----
// отобратьГорящие(items, предел) отдаёт массив ЭЛЕМЕНТОВ по убыванию срочности — см.
// docs/СРОЧНОСТЬ.md §7. Обе защиты (порог и вырожденность) живут внутри неё, а не в графе:
// иначе их пришлось бы повторять в каждом месте показа.
if (typeof отобратьГорящие === "function"){
  /* Пачки — ЛИТЕРАЛАМИ, а не через addItem: каждый addItem зовёт persist(), и семьдесят
     элементов превратились бы в семьдесят записей на диск посреди проверки. Формула чистая,
     ей настоящий элемент из S.items не нужен — важны только поля, которые она читает. */
  const пачка = [];
  for (let i = 0; i < 40; i++)
    пачка.push({kind:"task", done:false, status:"todo", due: Д(-1 - i % 3), priority: i % 4, updated: Date.now()});
  const г = отобратьГорящие(пачка, 8);
  t.push({имя:"горящих не больше предела", ок: г.length <= 8, факт:"их " + г.length});
  t.push({имя:"горящие отсортированы по убыванию срочности",
          ок: г.every((it, i) => i === 0 || urgency(г[i-1]) >= urgency(it)),
          факт:"первых три: " + г.slice(0,3).map(it => urgency(it).toFixed(2)).join(", ")});
  t.push({имя:"в горящие не попадает то, что ниже порога",
          ок: г.every(it => urgency(it) >= 0.20),
          факт:"минимальный балл в выборке: " + (г.length ? Math.min.apply(null, г.map(urgency)).toFixed(2) : "—")});

  const одинаковые = [];
  for (let i = 0; i < 30; i++)
    одинаковые.push({kind:"task", done:false, status:"todo", due:null, priority:0, updated: Date.now()});
  t.push({имя:"тридцать одинаковых пустых задач не дают горящих (вырожденный отбор)",
          ок: отобратьГорящие(одинаковые, 8).length === 0,
          факт:"их " + отобратьГорящие(одинаковые, 8).length});
} else {
  t.push({имя:"отбор горящих ещё не реализован — 4 проверки пропущены", ок:true,
          факт:"функция отобратьГорящие появится в core.js рядом с urgency"});
}

// прибираем за собой: сценарии крутятся на демо-данных, но мусор из 70 задач сломал бы
// следующие проверки в этом же прогоне
мусор.forEach(it => hardDeleteItem(it.id));
return t;

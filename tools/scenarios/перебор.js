/* ПЕРЕБОР МАРШРУТОВ — десятки случаев по зерну, в каждом режиме, по спецификации из шапки маршруты.js.
   Сами случаи, метрики и временный граф — в ui/js/routelab.js (его же листает галерея
   index.html?dev&routes-gallery). Здесь — только таблица: по режиму сумма нарушений, худшие случаи,
   устойчивость к посторонним правкам и скорость сборки на 520 нодах. Пока это ЗАМЕР (ок у справочных
   строк всегда), пороги — по мере того, как классы нарушений закрываются. */
const t = [];
if (typeof RouteLab === "undefined")
  await new Promise((ok, err) => { const s = document.createElement("script"); s.src = "js/routelab.js?v=" + Date.now(); s.onload = ok; s.onerror = () => err(new Error("routelab.js не загрузился")); document.head.appendChild(s); });
const т0 = performance.now();
const р = RouteLab.прогнать();
t.push({имя: "перебор: случаев " + р.случаев + " × режимов " + RouteLab.РЕЖИМЫ.length + " (справка)", ок: true, факт: "за " + ((performance.now() - т0) / 1000).toFixed(1) + " с"});
const поля = ["пер", "нав", "разв", "назад", "прямо", "впритык", "уНоды", "колен", "связей"];
for (const m of RouteLab.РЕЖИМЫ) {
  const и = р.итог[m]; if (!и) continue;
  t.push({имя: "перебор " + m + ": нарушения (справка)", ок: true, факт: поля.map(k => k + " " + и[k]).join(", ")});
  const х = р.худшие[m] || [];
  if (х.length) t.push({имя: "перебор " + m + ": худшие случаи (справка)", ок: true,
    факт: х.map(c => c.имя + " [" + ["пер", "нав", "разв", "назад", "прямо", "впритык"].filter(k => c.м[k]).map(k => k + c.м[k]).join(" ") + "]").join("; ")});
  const у = р.уст[m];
  if (у) t.push({имя: "перебор " + m + ": устойчивость — сменилось без причины (справка)", ок: true,
    факт: "сдвиг чужой ноды " + у.сдвиг + ", переименование " + у.имя + ", новая нода в стороне " + у.нова + " (случаев " + у.случаев + ")"});
}
t.push({имя: "перебор: сборка маршрутов на 520 нодах (справка)", ок: true, факт: Object.entries(р.ск).map(([m, v]) => m + " " + v.toFixed(1) + " мс").join(", ")});
return t;
